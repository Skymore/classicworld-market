"""Rebuild the collector's offline NPC buy-back fallback from tracked references."""
import json
from pathlib import Path


def build(root):
    rows = {}
    references = root / 'data/reference'
    for row in json.loads((references / 'mapledex/items.json').read_text(encoding='utf-8'))['items']:
        if isinstance(row.get('price'), (int, float)) and row['price'] > 0:
            rows[int(row['id'])] = row['price']
    for row in json.loads((references / 'niadb/items.json').read_text(encoding='utf-8')):
        try:
            stats = json.loads(row.get('stats') or '{}')
            item = int(row['iconKey'])
        except (ValueError, KeyError, TypeError):
            continue
        price = stats.get('price')
        if isinstance(price, (int, float)) and price > 0:
            rows[item] = price
    rows = {k: v for k, v in rows.items() if k // 1000000 in (1, 2, 3, 4)}
    header = ('"""NPC buy-back fallback from tracked data/reference/{mapledex,niadb}/items.json.\n'
              'Generated by tools/build_grind_npc_prices.py; NiaDB overrides Mapledex.\n'
              'Prices are not shop purchase prices. See THIRD_PARTY_NOTICES.md.\n"""\n\n')
    lines = ''.join(f'    {item}: {price!r},\n' for item, price in sorted(rows.items()))
    (root / 'grind_npc_prices.py').write_text(header + 'NPC_SELL = {\n' + lines + '}\n', encoding='utf-8')


if __name__ == '__main__':
    build(Path(__file__).resolve().parents[1])
