"""Writes desktop/grind-live.css: the client's rules for the live grind view,
scoped under .grind-live-view, so the website shows the same view
(src/pages/grind.tsx imports it; the client keeps using style.css).

Run after changing those rules in desktop/style.css:
    python frontend/scripts/live-css.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / 'desktop'
CLASSES = {
    'grind-tiles', 'grind-tile', 'grind-who', 'grind-buffs', 'grind-buff-list', 'grind-buff', 'grind-rate-panels',
    'grind-grid', 'grind-accounts', 'grind-account-row', 'grind-mesos', 'grind-kills', 'grind-attack-distribution',
    'grind-follow', 'grind-row', 'grind-combat', 'party-metrics', 'party-heading', 'ov-team-row', 'grind-empty',
    'well', 'well-h', 'note', 'amount', 'quantity', 'money', 'notable', 'mesos-icon',
}


def blocks(text):
    """Top-level (prelude, body) pairs."""
    out, depth, start, prelude = [], 0, 0, ''
    for i, ch in enumerate(text):
        if ch == '{':
            if depth == 0:
                prelude, start = text[start:i].strip(), i + 1
            depth += 1
        elif ch == '}':
            depth -= 1
            if depth == 0:
                out.append((prelude, text[start:i]))
                start = i + 1
    return out


def wanted(selector):
    names = set(re.findall(r'\.([a-zA-Z][\w-]*)', selector))
    return names & CLASSES and not names & {'grind-page', 'app-header', 'overlay', 'ov'}


def scope(selector):
    return ','.join('.grind-live-view ' + s.strip() for s in selector.split(','))


def rules(text):
    out = []
    for prelude, body in blocks(text):
        if prelude.startswith('@media'):
            inner = rules(body)
            if inner:
                out.append(prelude + '{' + ''.join(inner) + '}')
        elif not prelude.startswith('@') and wanted(prelude):
            out.append(scope(prelude) + '{' + body.strip() + '}')
    return out


css = re.sub(r'/\*.*?\*/', '', (ROOT / 'style.css').read_text(encoding='utf-8'), flags=re.S)
lines = rules(css)
(ROOT / 'grind-live.css').write_text(
    '/* Generated by frontend/scripts/live-css.py from style.css: the live grind view on the website. */\n'
    + '\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
print(len(lines), 'rules')
