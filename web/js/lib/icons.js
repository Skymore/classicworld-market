// Pixel icons from design/mockups-v2/mock.html (12-cell grid, currentColor).
// `I.leaf(size)` is a function; the rest are ready SVG strings.
export function px(art, size, palette = {}) {
  const rows = art.trim().split('\n').map((r) => r.trim());
  const w = rows[0].length, h = rows.length;
  let rects = '';
  rows.forEach((row, y) => {
    for (let x = 0; x < w;) {
      const c = row[x];
      if (c === '.') { x++; continue; }
      let run = 1;
      while (row[x + run] === c) run++;
      rects += `<rect x="${x}" y="${y}" width="${run}" height="1" fill="${palette[c] || 'currentColor'}"/>`;
      x += run;
    }
  });
  return `<svg class="px" viewBox="0 0 ${w} ${h}" width="${size}" height="${Math.round(size * h / w)}" shape-rendering="crispEdges" aria-hidden="true">${rects}</svg>`;
}
